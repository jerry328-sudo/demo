// Regenerate the shipped example with exactly the same learner used in the browser.
import { writeFileSync } from 'node:fs';
import './model.js';
const { Trainer, Policy, evaluate } = globalThis.CartPoleDemo;

const trainer = new Trainer(42);
while (trainer.episodes < 400) trainer.trainBatch();
const policy = new Policy();
policy.load(trainer.bestParameters);
const heldOut = evaluate(policy, 20000, 100);
if (heldOut.mean < 450) throw new Error(`Example failed held-out evaluation: ${heldOut.mean}`);
const example = {
  seed: 42,
  episodes: trainer.episodes,
  validationMean: trainer.bestScore,
  heldOutSeed: 20000,
  heldOutEpisodes: 100,
  heldOutMean: heldOut.mean,
  parameters: policy.snapshot()
};
writeFileSync(new URL('./example.js', import.meta.url),
  '// Generated by npm run train:cartpole; no hand-written controller.\n' +
  `globalThis.CartPoleDemo.example = ${JSON.stringify(example, null, 2)};\n`);
console.log(`Saved 4→8→2 policy trained for ${trainer.episodes} episodes; held-out mean ${heldOut.mean}/500.`);
